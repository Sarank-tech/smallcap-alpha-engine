# MAIN PIPELINE ORCHESTRATOR
# ------------------------------------------------------------------------------
def main():
    import argparse
    parser = argparse.ArgumentParser(description="Stage 5: Portfolio & Sell Strategy Engine")
    parser.add_argument(
        "--capital", "--portfolio-size",
        type=float,
        default=1000000.0,
        help="Total portfolio capital amount in INR (default: 1000000)",
    )
    args, _ = parser.parse_known_args()
    CONFIG["REFERENCE_PORTFOLIO_INR"] = args.capital

    logger.info("=" * 80)
    logger.info(f"STAGE 5: PORTFOLIO & SELL STRATEGY ENGINE STARTED (Capital: ₹{CONFIG['REFERENCE_PORTFOLIO_INR']:,.2f})")
    logger.info("=" * 80)

    # Step 1: Load Stage 4 Rankings
    df_rankings = load_stage4_rankings()

    # Step 2: Compute Portfolio Allocation Weights
    df_weighted = calculate_portfolio_weights(df_rankings)

    # Step 3: Generate Strategy for each position
    plan_rows = []
    for _, row in df_weighted.iterrows():
        strat = generate_position_strategy(row)
        plan_rows.append(strat)

    df_plan = pd.DataFrame(plan_rows)

    # Step 4: Export CSV: portfolio_plan.csv
    csv_cols = [
        "Rank", "Ticker", "Final Score", "Allocation %", "Position Size (INR)",
        "Buy Priority", "Risk Level", "Suggested Holding Period",
        "Slab-wise Profit Booking", "Stop Loss Rule", "Thesis Break Rules",
        "Investment Category", "Classification", "Investment Thesis"
    ]
    df_plan[csv_cols].to_csv(OUTPUT_PLAN_CSV, index=False)
    logger.info(f"Saved {OUTPUT_PLAN_CSV.name} ({len(df_plan)} rows).")

    # Step 5: Generate Markdown Report
    generate_portfolio_markdown_report(df_plan)

    # Step 6: Console Summary Output
    print("\n" + "=" * 140)
    print("STAGE 5: PORTFOLIO & SELL STRATEGY ENGINE — MASTER POSITION ALLOCATION PLAN")
    print("=" * 140)
    print(f"{'Rank':<5} | {'Ticker':<14} | {'Score':>6} | {'Alloc %':>8} | {'Pos Size (₹)':>14} | {'Buy Priority':<32} | {'Suggested Holding Period'}")
    print("-" * 140)
    for _, r in df_plan.iterrows():
        print(
            f"#{r['Rank']:<4} | {r['Ticker']:<14} | {r['Final Score']:>6.2f} | "
            f"{r['Allocation %']:>7.2f}% | ₹{r['Position Size (INR)']:>12,.2f} | "
            f"{r['Buy Priority']:<32} | {r['Suggested Holding Period']}"
        )
    print("=" * 140)

    print("\nSLAB-WISE PROFIT BOOKING & EXIT RULES SUMMARY:")
    for _, r in df_plan.iterrows():
        print(f"\n[{r['Ticker']} | Rank #{r['Rank']} | Alloc: {r['Allocation %']:.2f}% | Position: ₹{r['Position Size (INR)']:,.2f}]")
        print(f"  Priority     : {r['Buy Priority']}")
        print(f"  Profit Slabs : {r['Slab-wise Profit Booking']}")
        print(f"  Stop Loss    : {r['Stop Loss Rule']}")
        print(f"  Thesis Break : {r['Thesis Break Rules']}")

    logger.info("Stage 5 Portfolio & Sell Strategy Engine successfully completed.")


if __name__ == "__main__":
    main()
