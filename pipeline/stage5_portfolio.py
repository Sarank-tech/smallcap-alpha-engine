# Suppress warnings
warnings.filterwarnings("ignore")

# ------------------------------------------------------------------------------
# CONFIGURATION & CONSTANTS
# ------------------------------------------------------------------------------
CONFIG = {
    "REFERENCE_PORTFOLIO_INR": 1000000.0,  # ₹10 Lakhs reference portfolio size
    "HARD_STOP_LOSS_PCT": -12.0,            # Hard stop loss percentage from entry
    "TRAILING_STOP_LOSS_PCT": 15.0,         # Trailing stop loss percentage from peak
    "MAX_SINGLE_STOCK_WEIGHT": 25.0,        # Maximum allocation cap per stock (%)
    "MIN_SINGLE_STOCK_WEIGHT": 5.0,         # Minimum allocation floor per stock (%)
}

BASE_DIR = Path(__file__).resolve().parent.parent / "outputs"  # smallcap-alpha-engine/outputs/
INPUT_RANKING_CSV = BASE_DIR / "final_multibagger_ranking.csv"
OUTPUT_PLAN_CSV = BASE_DIR / "portfolio_plan.csv"
OUTPUT_STRATEGY_MD = BASE_DIR / "portfolio_strategy_report.md"
