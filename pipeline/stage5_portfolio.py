#!/usr/bin/env python3
"""
NSE Smallcap Multibagger Discovery System — Stage 5: Portfolio & Sell Strategy Engine
======================================================================================
Program Name: 5_portfolio_sell_strategy_engine.py

Objective:
Converts Stage 4 investment rankings (`final_multibagger_ranking.csv`) into actionable
portfolio allocation decisions, risk parameters, and disciplined profit-booking / exit strategies.

Stage 5 Core Functions:
1. Capital Allocation & Position Sizing:
   - Dynamic weight calculation based on Final Score & Conviction Rank.
   - Position allocation % (normalized to 100% portfolio equity).
   - Sample position size calculation for a standard ₹10,00,000 (₹10 Lakh) reference portfolio.
2. Risk & Horizon Management:
   - Buy Priority (High / Medium / Low / Watchlist)
   - Risk Level (Low / Moderate / High)
   - Suggested Holding Period (18-24 Months, 12-18 Months, 6-12 Months)
3. Slab-Wise Profit Booking Framework:
   - Slab 1: Book 20% profit at +25% gain
   - Slab 2: Book 20% profit at +50% gain
   - Slab 3: Book 20% profit at +75% gain
   - Slab 4: Book 20% profit at +100% gain (100% return / Multibagger milestone)
   - Runner: Hold remaining 20% with trailing stop loss to capture extended upside.
4. Exit Strategy & Fundamental Thesis Break Triggers:
   - Initial Hard Stop Loss (e.g., -12.0% from entry price)
   - Trailing Stop Loss (e.g., 15% trailing from peak once gain exceeds +50%)
   - Fundamental Thesis Break Rules (Debt/Equity > 0.50, 2 consecutive negative earnings quarters, promoter selling).

Outputs Generated:
1. portfolio_plan.csv          - Comprehensive portfolio allocation & sell strategy matrix.
2. portfolio_strategy_report.md - Structured executive report detailing portfolio execution rules.
"""

